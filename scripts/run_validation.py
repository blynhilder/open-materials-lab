"""一键复现: 计算 Si/Al/Fe 粉末 XRD, 与 pymatgen 交叉验证, 输出表格与图.

Usage:  python scripts/run_validation.py
Outputs: results/validation_<El>.csv, results/validation_summary.md, figures/<El>_xrd_own_vs_pymatgen.png
"""
from __future__ import annotations

import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from xtal import CU_KA1, gaussian_profile, read_cif
from xtal.compare import compare, pymatgen_form_factor

MATERIALS = [
    ("Si", "data/Si_COD_9011998.cif", "diamond cubic, Fd-3m, COD 9011998"),
    ("Al", "data/Al_COD_9012002.cif", "FCC, Fm-3m, COD 9012002"),
    ("Fe", "data/Fe_COD_9008536.cif", "α-Fe BCC, Im-3m, COD 9008536"),
]
TT_RANGE = (10.0, 120.0)


def run(material, cif_rel, label, outdir_fig, outdir_res):
    cif = os.path.join(ROOT, cif_rel)
    xt = read_cif(cif, material)
    rows, own, pat = compare(xt, cif, CU_KA1, TT_RANGE)
    rows_pf, _, _ = compare(xt, cif, CU_KA1, TT_RANGE, form_factor=pymatgen_form_factor)
    for r, r2 in zip(rows, rows_pf):
        r["dI_same_f"] = r2["dI"]
    with open(os.path.join(outdir_res, f"validation_{material}.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)

    grid = np.linspace(*TT_RANGE, 11001)
    y_own = gaussian_profile(own, grid, fwhm=0.15)
    fig, ax = plt.subplots(figsize=(9, 4.8))
    ax.plot(grid, y_own, lw=1.0, color="C0", label="own code (xtal), Gaussian FWHM=0.15°")
    ax.vlines([p.two_theta for p in own], 0, [p.intensity for p in own], color="C0", lw=2.5, alpha=0.5,
              label="own code sticks")
    ax.vlines(pat.x, 0, -np.asarray(pat.y), color="C3", lw=2.0, label="pymatgen XRDCalculator (mirrored)")
    ax.axhline(0, color="k", lw=0.6)
    for p in own:
        ax.annotate("+".join("".join(map(str, f)) for f in p.families), (p.two_theta, p.intensity + 3),
                    ha="center", fontsize=8)
    ax.set_xlim(*TT_RANGE)
    ax.set_ylim(-110, 118)
    ax.set_xlabel("2θ (degrees), Cu Kα1 λ = 1.5406 Å")
    ax.set_ylabel("relative intensity (max = 100)")
    ax.set_title(f"{material} ({label}) — TEACHING SIMULATION, NOT EXPERIMENTAL DATA")
    ax.text(0.99, 0.02, "No Debye–Waller, no absorption, no Kα2, no instrument function",
            transform=ax.transAxes, ha="right", va="bottom", fontsize=8, color="gray")
    ax.legend(loc="upper right", fontsize=8)
    fig.tight_layout()
    path = os.path.join(outdir_fig, f"{material}_xrd_own_vs_pymatgen.png")
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return xt, rows, path


def main():
    fig_dir = os.path.join(ROOT, "figures")
    res_dir = os.path.join(ROOT, "results")
    os.makedirs(fig_dir, exist_ok=True)
    os.makedirs(res_dir, exist_ok=True)
    md = ["# Validation summary (auto-generated by scripts/run_validation.py)", "",
          f"λ = {CU_KA1} Å (Cu Kα1), 2θ range {TT_RANGE}, Debye–Waller OFF. "
          "Teaching simulation — not experimental measurement.", "",
          "dI_same_f = own − pymatgen when own code uses pymatgen's form-factor table (diagnostic).", ""]
    for m, cif, label in MATERIALS:
        xt, rows, path = run(m, cif, label, fig_dir, res_dir)
        md += [f"## {m} — {label}  (a = {xt.a} Å, {xt.n_atoms} atoms/cell)", "",
               "| hkl | mult | d (Å) | 2θ own | 2θ pmg | Δ2θ | I own | I pmg | ΔI | ΔI (same f) |",
               "|---|---|---|---|---|---|---|---|---|---|"]
        for r in rows:
            md.append(f"| {r['hkl']} | {r['mult']} | {r['d_own']:.4f} | {r['tt_own']:.4f} | {r['tt_pmg']:.4f} | "
                      f"{r['dtt']:.1e} | {r['I_own']:.2f} | {r['I_pmg']:.2f} | {r['dI']:+.2f} | {r['dI_same_f']:+.1e} |")
        md += ["", f"Figure: `figures/{os.path.basename(path)}`", ""]
        print(f"{m}: {len(rows)} peaks, max|Δ2θ|={max(abs(r['dtt']) for r in rows):.2e}°, "
              f"max|ΔI|={max(abs(r['dI']) for r in rows):.3f}, max|ΔI same f|={max(abs(r['dI_same_f']) for r in rows):.1e}")
    open(os.path.join(res_dir, "validation_summary.md"), "w").write("\n".join(md) + "\n")


if __name__ == "__main__":
    main()
